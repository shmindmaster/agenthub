"""Owner-operated local controls. No automatic budget/reset or provider requests."""
import argparse
import hashlib
import json
import pathlib
import sys

from content_runtime import Ledger


def accept_manifest(ledger, namespace, key, manifest):
    """Verify saved evidence files; human/tool reviewers remain responsible for QA."""
    gates = json.loads(manifest.read_text(encoding="utf-8"))
    for gate in gates.values():
        evidence = pathlib.Path(gate["evidence_path"])
        if not evidence.is_absolute() or not gate.get("reviewer"):
            raise RuntimeError("Acceptance requires absolute evidence paths and an identified reviewer")
        if hashlib.sha256(evidence.read_bytes()).hexdigest() != gate.get("evidence_sha256"):
            raise RuntimeError("Acceptance evidence file hash mismatch")
    return ledger.accept(namespace, key, gates)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("status")
    configure = sub.add_parser("configure", help="Set an owner-approved lifetime aggregate ceiling; never resets spend")
    configure.add_argument("--bucket", required=True)
    configure.add_argument("--ceiling", required=True, type=int)
    freeze = sub.add_parser("freeze", help="Stop new reservations at current commitments; preserve reuse/recovery")
    freeze.add_argument("--bucket", required=True)
    accept = sub.add_parser("accept", help="Attach completed QA evidence to exact generated bytes")
    accept.add_argument("--namespace", required=True)
    accept.add_argument("--cache-key", required=True)
    accept.add_argument("--manifest", required=True, type=pathlib.Path)
    args = parser.parse_args(argv)
    try:
        ledger = Ledger()
        if args.command == "configure":
            ledger.configure(args.bucket, args.ceiling)
        elif args.command == "freeze":
            with ledger.connect(True) as con:
                con.execute("UPDATE budgets SET ceiling=? WHERE bucket=?",
                            (ledger.committed(con, args.bucket), args.bucket))
        elif args.command == "accept":
            row = accept_manifest(ledger, args.namespace, args.cache_key, args.manifest)
            print(json.dumps({"acceptance_state": row["state"], "output_sha256": row["sha256"]}))
            return 0
        print(json.dumps(ledger.status()))
        return 0
    except (RuntimeError, OSError, ValueError, KeyError, TypeError):
        print("Content control failed; inspect local policy/evidence without retrying provider submission", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
